-- ── clipboard history for the lifelog ────────────────────────────────────────
-- Added 2026-10-07. Every clipboard change becomes one JSON row in
-- ~/.local/state/lifelog/clipboard/YYYY-MM-DD.jsonl (dir 0700, files 0600, 30
-- days); the lifelog ingester (scripts/lifelog/clipboard.py) copies new rows
-- into the store every 5 min, where they are kept 90 days (policy.toml).
--
-- Rows: kind = "copy"   text (capped at 20,000 chars), a URL, file paths, or an
--                       image's type and pixel size (never the bytes)
--              "secret" an API key, JWT, private key, 2FA code, password-like
--                       token, or a copy the clipboard was cleared after within
--                       60 s (what password managers do): rule + length only
--              "skipped" a copy marked do-not-record (Bitwarden Desktop, Wispr's
--                       own pastes, 1Password, Raycast) or made while a password
--                       manager was in front: reason + app only
-- Secrets are recognised HERE, so they never reach disk; the ingester runs
-- redact.py over everything again. Plain-text copies are held 60 s before they
-- are written, so a clear-after-copy can still turn them into a secret row.
--
-- The front app is recorded by name and bundle id only: a window title would
-- be an accessibility call on Hammerspoon's main thread (see init.lua's
-- timeout note). Join to ActivityWatch's `windows` rows at query time instead.
-- Every callback is wrapped in pcall; errors go to the Hammerspoon console.
local M = {}

