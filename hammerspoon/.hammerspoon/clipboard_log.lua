-- hs.pasteboard's functions take the pasteboard name as an optional FIRST argument; an explicit nil
-- there isn't the same as leaving it out, so only pass it when testing on a private pasteboard.
local function P(fn, pb, ...)
  if pb then return fn(pb, ...) end
  return fn(...)
end


-- Width and height in pixels from a PNG or TIFF header, without decoding the image.
local function pixelSize(uti, data)
  if not data then return nil end
  if uti == "public.png" and #data >= 24 then
    local w, h = string.unpack(">I4I4", data, 17)
    return w, h
  end
  if uti == "public.tiff" and #data >= 8 then
    local bo = data:sub(1, 2) == "II" and "<" or ">"
    local ifd = string.unpack(bo .. "I4", data, 5)
    if ifd + 2 > #data then return nil end
    local n, w, h = string.unpack(bo .. "I2", data, ifd + 1), nil, nil
    for i = 0, math.min(n, 64) - 1 do
      local at = ifd + 3 + i * 12
      if at + 11 > #data then break end
      local tag, typ = string.unpack(bo .. "I2I2", data, at)
      local v = typ == 3 and string.unpack(bo .. "I2", data, at + 8) or string.unpack(bo .. "I4", data, at + 8)
      if tag == 256 then w = v elseif tag == 257 then h = v end
    end
    return w, h
  end
  return nil
end

-- HTML or RTF with no plain-text version: strip it to text in Lua. Not readStyledText: importing HTML
-- into an attributed string runs WebKit in a nested run loop on the main thread, which re-enters
-- Hammerspoon's other callbacks (and hangs `hs -c` with "already recursing").
local ENTITIES = { amp = "&", lt = "<", gt = ">", quot = '"', apos = "'", nbsp = " " }

-- Cut out every <script>…</script> block in one pass. A gsub with `.-` would rescan to the end of the
-- text from every unclosed opening tag (quadratic: ~1 min of frozen main thread at 400 KB); here an
-- opening tag with no closing tag drops the rest and stops.
local function dropBlocks(html, open, close)
  local out, i = {}, 1
  while true do
    local a = html:find(open, i)
    if not a then break end
    out[#out + 1] = html:sub(i, a - 1) .. " "
    local _, e = html:find(close, a)
    if not e then i = #html + 1; break end
    i = e + 1
  end
  out[#out + 1] = html:sub(i)
  return table.concat(out)
end

local function richToPlain(pb, types)
  local function data(uti) return has(types, uti) and P(hs.pasteboard.readDataForUTI, pb, uti) or nil end
  local html = data("public.html")
  if html then
    html = dropBlocks(html:sub(1, 400000), "<[Ss][Cc][Rr][Ii][Pp][Tt]", "</[Ss][Cc][Rr][Ii][Pp][Tt]>")
    html = dropBlocks(html, "<[Ss][Tt][Yy][Ll][Ee]", "</[Ss][Tt][Yy][Ll][Ee]>"):gsub("<[Bb][Rr]%s*/?>", "\n")
      :gsub("</?[Pp]>", "\n"):gsub("<[^<>]*>", ""):gsub("&(%a+);", function(e) return ENTITIES[e:lower()] end)
      :gsub("&#(%d+);", function(d)
        local n = tonumber(d)
        return n and n < 0x110000 and utf8.char(n) or nil
      end)
    return html
  end
  local rtf = data("public.rtf")
  if rtf then
    rtf = rtf:sub(1, 400000):gsub("{\\%*[^{}]*}", ""):gsub("\\par[d]?%s?", "\n"):gsub("\\'%x%x", "")
      :gsub("\\%a+%-?%d*%s?", ""):gsub("[{}]", "")
    return rtf
  end
  return nil
end

local function frontApp()
  local app = hs.application.frontmostApplication()
  if not app then return "?", nil end
  return app:name() or "?", app:bundleID()
end

-- Nothing but whitespace, NULs and invisible characters (zero-width space/joiners, word joiner, BOM,
-- no-break space). Bitwarden's browser extension "clears" the clipboard on Chromium by writing "\0",
-- so that has to count as a clear, not as a new copy.
local function blank(s)
  return not s:gsub("[\0%s]", ""):gsub("\226\128[\139-\141]", ""):gsub("\226\129\160", "")
    :gsub("\239\187\191", ""):gsub("\194\160", ""):find(".")
end
M.blank = blank

-- What is on pasteboard `pb` (nil = the general one) right now, as a row, or "empty".
local function capture(pb, now)
  local PB = hs.pasteboard
  local allTypes = P(PB.pasteboardTypes, pb) or {}
  local appName, bundle = frontApp()
  local row = { t = isoAt(now), app = appName, bundle = bundle, types = keptTypes(allTypes) }
  if #row.types == 0 then row.types = nil end

  -- Markers and password managers first: nothing else is read from these copies.
  for _, ty in ipairs(allTypes) do
    if MARKERS[ty] then row.kind, row.reason = "skipped", MARKERS[ty]; break end
  end
  if not row.kind and bundle and (PASSWORD_APPS[bundle] or (appName or ""):find("1Password", 1, true)) then
    row.kind, row.reason = "skipped", "password-manager"
  end
  if row.kind then return row end
  if has(allTypes, "org.nspasteboard.source") then
    local src = P(PB.readDataForUTI, pb, "org.nspasteboard.source")
    if src and #src < 200 then row.source = src end
  end

  row.kind = "copy"
  if has(allTypes, "public.file-url") then
    local paths = {}
    for _, u in ipairs(P(PB.readURL, pb, true) or {}) do
      if type(u) == "table" and u.filePath then paths[#paths + 1] = u.filePath end
      if #paths >= 50 then break end
    end
    if #paths > 0 then row.paths, row.key = paths, "files:" .. table.concat(paths, "\n"); return row end
  end

  local text = P(PB.readString, pb)
  if text == nil then text = richToPlain(pb, allTypes) end
  if text and not blank(text) then
    -- Cap first: every rule below is a Lua pattern scan on the main thread.
    local capped, trunc = cap(text, M.MAX_CHARS)
    local rule = secretRule(capped)
    row.len = ulen(text)
    if rule then
      row.kind, row.rule = "secret", rule
      return row
    end
    row.text = maskAll(capped)
    row.trunc = trunc or nil
    if not trunc and trim(capped):match("^%a[%w%+%.%-]*://%S+$") then row.url = true end
    row.key, row.held = "text:" .. capped, true
    return row
  end

  for _, uti in ipairs(IMAGE_TYPES) do
    if has(allTypes, uti) then
      local w, h = pixelSize(uti, (uti == "public.png" or uti == "public.tiff") and P(PB.readDataForUTI, pb, uti) or nil)
      if not w then
        local img = P(PB.readImage, pb)
        local sz = img and img:size()
        if sz then w, h, row.points = math.floor(sz.w), math.floor(sz.h), true end
      end
      row.image = { uti = uti, w = w, h = h }
      row.key = "image:" .. uti .. ":" .. tostring(w) .. "x" .. tostring(h) .. ":" .. row.t
      return row
    end
  end
  -- Whitespace only, or a clear (pbcopy </dev/null). Some other type: keep the type names.
  if text ~= nil or #allTypes == 0 then return "empty" end
  return row
end
M.capture = capture

-- ── the log ─────────────────────────────────────────────────────────────────

local function push(row)
  row.key, row.held, row.at = nil, nil, nil
  if row.rep == 1 then row.rep = nil end
  local ok, line = pcall(hs.json.encode, row)
  if not ok or not line then
    row.text = nil
    row.enc = "failed"
    ok, line = pcall(hs.json.encode, row)
  end
  if ok and line then buf[#buf + 1] = { day = row.t:sub(1, 10), line = line } end
end

local emptyCc, emptyAt = nil, 0  -- an empty clipboard seen at change emptyCc, not yet confirmed (see check)

local function release(now, force)
  -- While an empty clipboard is unconfirmed, keep holding: it may yet turn the held copy into a secret.
  if pending and (force or (not emptyCc and now - pending.at >= M.HOLD)) then
    push(pending)
    pending = nil
  end
end

local function ensureDir()
  if hs.fs.attributes(M.DIR, "mode") == "directory" then return end
  local parent = M.DIR:match("^(.*)/[^/]+$")
  if hs.fs.attributes(parent, "mode") ~= "directory" then hs.fs.mkdir(parent) end
  hs.fs.mkdir(M.DIR)
  hs.task.new("/bin/chmod", nil, { "700", M.DIR }):start()
end

local function flush()
  if #buf == 0 then return end
  ensureDir()
  local byDay = {}
  for _, r in ipairs(buf) do
    byDay[r.day] = byDay[r.day] or {}
    table.insert(byDay[r.day], r.line)
  end
  buf = {}
  for day, lines in pairs(byDay) do
    local path = M.DIR .. "/" .. day .. ".jsonl"
    local fresh = hs.fs.attributes(path, "mode") == nil
    local fh = io.open(path, "a")
    if fh then
      fh:write(table.concat(lines, "\n") .. "\n")
      fh:close()
      if fresh then hs.task.new("/bin/chmod", nil, { "600", path }):start() end
    else
      print("clipboard_log: can't open " .. path)
    end
  end
end

local function prune()
  local today = os.date("%Y-%m-%d")
  if today == lastPrune or hs.fs.attributes(M.DIR, "mode") ~= "directory" then return end
  lastPrune = today
  local cutoff = os.date("%Y-%m-%d", os.time() - M.KEEP_DAYS * 86400)
  for f in hs.fs.dir(M.DIR) do
    local day = f:match("^(%d%d%d%d%-%d%d%-%d%d)%.jsonl$")
    if day and day < cutoff then os.remove(M.DIR .. "/" .. f) end
  end
end

-- The clipboard stayed empty: a text copy held from just before is a password manager wiping a secret.
local function cleared()
  if pending and emptyAt - pending.at <= M.HOLD then
    pending.kind, pending.rule, pending.text, pending.trunc, pending.url = "secret", "cleared", nil, nil, nil
    push(pending)
    pending = nil
  end
  emptyCc = nil
end

local function take(row, cc, now, jumped)
  row.cc, row.at = cc, now
  if row.kind == "skipped" then
    lastSkipAt = now
    release(now, true)
    push(row)
    return
  end
  if row.key and row.key == lastKey then
    -- The same content again. Right after a hidden change it is an app restoring the clipboard, not a copy.
    if jumped or now - lastSkipAt < 3 then return end
    if pending then pending.rep = (pending.rep or 1) + 1; return end
  end
  lastKey = row.key
  release(now, true)
  if row.held then pending = row else push(row) end
end

local function guarded(name, fn)
  return function(...)
    local ok, err = pcall(fn, ...)
    if not ok then print("clipboard_log " .. name .. " error: " .. tostring(err)) end
  end
end

M.CONFIRM = 0.5  -- seconds an empty clipboard must stay empty to count as a clear

-- One clipboard change: called by the watcher, and by the backup timer if the watcher missed it.
-- An empty clipboard is only a clear once it stays empty. pbcopy and most writers clear first (which
-- bumps changeCount) and write a few ms later (which doesn't), so the watcher can land in between;
-- taking that as a clear would turn the held copy into a false secret and lose the new text.
local check
local function recheck()
  if M.recheckTimer then M.recheckTimer:stop() end
  M.recheckTimer = hs.timer.doAfter(M.CONFIRM, guarded("recheck", check))
end

check = function()
  local cc = P(hs.pasteboard.changeCount, M.PB)
  local now = hs.timer.secondsSinceEpoch()
  if cc == lastCc then
    if emptyCc ~= cc then return end
    local row = capture(M.PB, now)  -- same change, last seen empty: has the write landed?
    if row ~= "empty" then
      emptyCc = nil
      take(row, cc, now, false)
    elseif now - emptyAt >= M.CONFIRM then
      cleared()
    else
      recheck()
    end
    return
  end
  emptyCc = nil  -- a new change before the empty one was confirmed: not a clear we can vouch for
  local jumped = cc - lastCc >= 2  -- changes in between that we never saw (Wispr's paste + restore)
  lastCc = cc
  local row = capture(M.PB, now)
  if row == "empty" then
    emptyCc, emptyAt = cc, now
    recheck()
    return
  end
  take(row, cc, now, jumped)
end
M.check = check
local ok, w = pcall(function() return hs.pasteboard.watcher.new(guarded("watcher", check)) end)
if ok and w then
  M.watcher = w:start()
  -- Backup: a cheap changeCount comparison catches anything the watcher missed.
  M.backup = hs.timer.doEvery(2, guarded("backup", check))
else
  print("clipboard_log: pasteboard watcher unavailable (" .. tostring(w) .. "); polling every 0.5 s")
  M.backup = hs.timer.doEvery(0.5, guarded("poll", check))
end

M.flushTimer = hs.timer.doEvery(5, guarded("flush", function()
  release(hs.timer.secondsSinceEpoch(), false)
  flush()
  prune()
end))

-- Write what's held on reload or quit, so a reload doesn't lose the last minute.
local prevShutdown = hs.shutdownCallback
hs.shutdownCallback = function()
  pcall(function() release(0, true); flush() end)
  if prevShutdown then prevShutdown() end
end

-- For tests from `hs -c`: write everything now.
function M.flushNow()
  release(0, true)
  flush()
end

-- For tests from `hs -c`: watch a private named pasteboard instead of the general one (nil = back to
-- the general one), so a test never touches what Matt has copied. The watcher still fires only for the
-- general pasteboard; call M.check() after each test write.
function M.usePasteboard(name)
  release(0, true)
  M.PB, emptyCc, lastKey, lastSkipAt = name, nil, nil, 0
  lastCc = P(hs.pasteboard.changeCount, name)
end

pcall(prune)
return M
