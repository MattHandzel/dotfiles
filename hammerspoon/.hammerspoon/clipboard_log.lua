-- ── small helpers ───────────────────────────────────────────────────────────

local function isoAt(t)  -- same format as the Oops trail: 2026-10-07T20:15:03.123-07:00
  local s = math.floor(t)
  local z = os.date("%z", s)
  return os.date("%Y-%m-%dT%H:%M:%S", s) .. string.format(".%03d", math.floor((t - s) * 1000)) .. z:sub(1, 3) .. ":" .. z:sub(4, 5)
end

local function ulen(s) return utf8.len(s) or #s end

local function cap(s, n)  -- first n characters, cut on a character boundary
  local i = utf8.offset(s, n + 1)
  if i and i <= #s then return s:sub(1, i - 1), true end
  return s, false
end

local function has(list, x)
  for _, v in ipairs(list or {}) do if v == x then return true end end
  return false
end

-- Type names worth keeping: drop the dyn.* and legacy duplicates browsers add.
local function keptTypes(types)
  local out = {}
  for _, ty in ipairs(types or {}) do
    if not ty:match("^dyn%.") and not ty:match("PboardType$") and not ty:match("^CorePasteboardFlavorType")
        and not ty:match("^Apple ") and not ty:match("^NeXT ") then
      out[#out + 1] = ty
      if #out >= 12 then break end
    end
  end
  return out
end

-- ── secret rules (a port of redact.py's, which the ingester runs again) ──────
local SECRET = "[secret]"

-- name, Lua pattern for the prefix, character class of the rest, minimum rest length, extra check
local TOKENS = {
  { "anthropic-key", "sk%-ant%-", "[%w_%-]", 20 },
  { "openai-key", "sk%-", "[%w_%-]", 20, function(r) return r:find("%d") and r:find("%u") end },
  { "stripe-key", "[sr]k_live_", "%w", 16 }, { "stripe-key", "[sr]k_test_", "%w", 16 },
  { "sk-underscore-key", "sk_", "%w", 32, function(r) return r:find("%d") end },
  { "github-token", "gh[pousr]_", "%w", 30 },
  { "github-pat", "github_pat_", "[%w_]", 40 },
  { "slack-token", "xox[abposr]%-", "[%w%-]", 10 },
  { "slack-app-token", "xapp%-%d%-", "[%w%-]", 20 },
  { "aws-access-key", "A[KS]IA", "[%u%d]", 16, function(r) return #r == 16 end },
  { "google-api-key", "AIza", "[%w_%-]", 35 },
  { "gitlab-token", "glpat%-", "[%w_%-]", 20 },
  { "npm-token", "npm_", "%w", 36 },
  { "huggingface-token", "hf_", "%w", 30 },
  { "linear-key", "lin_api_", "%w", 32 },
  { "tailscale-key", "tskey%-%l+%-", "[%w%-]", 10 },
  { "ntfy-token", "tk_", "%w", 29 },
}

-- Replace every known token in s; returns the new text and the first rule that hit.
local function maskTokens(s)
  local hit
  for _, tk in ipairs(TOKENS) do
    local name, pre, cls, min, check = tk[1], tk[2], tk[3], tk[4], tk[5]
    s = s:gsub("%f[%w](" .. pre .. ")(" .. cls .. "+)", function(p, rest)
      if #rest >= min and (not check or check(rest)) then hit = hit or name; return SECRET end
    end)
  end
  s = s:gsub("%f[%w](%d+):AA([%w_%-]+)", function(d, rest)
    if #d >= 8 and #d <= 10 and #rest >= 33 then hit = hit or "telegram-bot-token"; return SECRET end
  end)
  s = s:gsub("%f[%w_%-]eyJ([%w_%-]+)%.eyJ([%w_%-]+)%.([%w_%-]*)", function(a, b)
    if #a >= 8 and #b >= 8 then hit = hit or "jwt"; return SECRET end
  end)
  s = s:gsub("([Bb]earer%s+)([%w%._~%+/%-]+=*)", function(p, v)
    if #v >= 16 then hit = hit or "authorization"; return p .. SECRET end
  end)
  return s, hit
end

local SECRET_KEYS = { "token", "secret", "password", "passwd", "passwrd", "apikey", "api_key", "api-key", "accesskey",
  "access_key", "access-key", "privatekey", "private_key", "private-key", "authkey", "auth_key", "auth-key",
  "sessionkey", "session_key", "session-key", "client_secret", "credential", "cookie" }
local NOT_VALUE = {}
for w in ("str string int integer bool boolean none null nil true false undefined optional any bytes text required " ..
    "yes no env redacted hidden secret example placeholder password token number object unknown empty missing default"):gmatch("%S+") do
  NOT_VALUE[w] = true
end

-- Matched as whole words only: as substrings they'd hit passenger, compass, bypass.
local SECRET_WORDS = { pass = true, pwd = true, passcode = true }

local function secretKey(k)
  k = k:lower()
  if k:find("tokens", 1, true) or k:find("tokeniz", 1, true) or k:find("cookies", 1, true) then return false end
  for _, w in ipairs(SECRET_KEYS) do if k:find(w, 1, true) then return true end end
  for w in k:gmatch("%a+") do if SECRET_WORDS[w] then return true end end
  return false
end

-- KEY=value / KEY: value / "key": "value" with a secret-sounding key. Every pattern here starts with a
-- frontier (%f), so a match is only tried where a run of word characters begins: without it a long run
-- is retried from every position and the scan goes quadratic on Hammerspoon's main thread.
local function maskAssign(s)
  local hit
  local function one(key, sep, q, val)
    if not secretKey(key) then return nil end
    local v = val
    if (#v < 6 and q == "") or NOT_VALUE[v:lower()] or v:match("^[xX%*%.#%?_%-]+$") or v:match("^<.*>$")
        or v:match("^%[secret%]") or v:match("^your") or v:match("^%d+$") and #v <= 5
        or v:match("^[%$%%/~]") or v:find("[%(%[{]") or v:match("^[%a_][%w_]*%.[%w_%.]+$") then
      return nil
    end
    hit = "assignment"
    return key .. sep .. q .. SECRET .. q
  end
  s = s:gsub("%f[%w_%.%-]([%w_%.%-]+[\"']?)(%s*[:=]%s*)([\"'])([^\"'\n]+)%3", function(k, sep, q, v) return one(k, sep, q, v) end)
  s = s:gsub("%f[%w_%.%-]([%w_%.%-]+[\"']?)(%s*[:=]%s*)([^%s\"'`,;&%)}%]]+)", function(k, sep, v)
    if v:sub(1, #SECRET) == SECRET then return nil end
    return one(k, sep, "", v)
  end)
  return s, hit
end

-- A segment that reads as random: upper, lower and digits each at least twice, class changing on 45%+ of steps.
local function randomLooking(seg)
  if #seg < 20 then return false end
  local up, lo, dg = select(2, seg:gsub("%u", "")), select(2, seg:gsub("%l", "")), select(2, seg:gsub("%d", ""))
  if math.min(up, lo, dg) < 2 then return false end
  local function cls(c) return c:match("%u") and 1 or c:match("%l") and 2 or c:match("%d") and 3 or 4 end
  local changes, prev = 0, nil
  for c in seg:gmatch(".") do
    local k = cls(c)
    if prev and k ~= prev then changes = changes + 1 end
    prev = k
  end
  return changes / (#seg - 1) >= 0.45
end

-- The catch-all: long random-looking runs that aren't URLs, hashes or uuids. A path keeps its readable parts.
local function maskRuns(s)
  local hit
  s = s:gsub("%S+", function(word)
    if #word < 32 or word:find("://", 1, true) or word:match("^www%.") or word:match("^data:") then return nil end
    return (word:gsub("[%w%+/=_%-]+", function(run)
      if #run < 32 or run:lower():match("^sha%d+%-") then return nil end
      local segs, alpha = {}, 0
      for seg in run:gmatch("[^/%._%-]+") do
        segs[#segs + 1] = seg
        if seg:match("^%a+$") then alpha = alpha + 1 end
      end
      if run:find("/", 1, true) and alpha >= 2 then
        return (run:gsub("[^/%._%-]+", function(seg)
          if randomLooking(seg) then hit = "random-token"; return SECRET end
        end))
      end
      for _, seg in ipairs(segs) do
        if randomLooking(seg) then hit = "random-token"; return SECRET end
      end
      if randomLooking((run:gsub("[_%-]", ""))) then hit = "random-token"; return SECRET end
    end))
  end)
  return s, hit
end

-- Everything above, over a whole text. Returns the masked text and the first rule that hit.
local function maskAll(s)
  if s:find("%-%-%-%-%-BEGIN [%u%d ]*PRIVATE KEY") then  -- private key blocks; one cut short by the cap runs to the end
    local out, i = {}, 1
    while true do
      local a = s:find("%-%-%-%-%-BEGIN [%u%d ]*PRIVATE KEY", i)
      if not a then break end
      local _, e = s:find("%-%-%-%-%-END [%u%d ]*PRIVATE KEY[%u ]*%-%-%-%-%-", a)
      out[#out + 1] = s:sub(i, a - 1) .. SECRET
      i = e and e + 1 or #s + 1
    end
    out[#out + 1] = s:sub(i)
    s = table.concat(out)
  end
  local n
  s, n = s:gsub("%f[%w%+%.%-](%a[%w%+%.%-]*://[^/%s:@]+:)[^/%s@]+(@)", "%1" .. SECRET .. "%2")  -- https://user:pass@host
  local h1, h2, h3
  s, h1 = maskTokens(s)
  s, h2 = maskAssign(s)
  s, h3 = maskRuns(s)
  return s, h1 or h2 or h3 or (n > 0 and "url-password" or nil)
end

local function classes(t)
  local n = 0
  -- Bytes 0x80+ (accented letters, emoji) count as lower-case letters, not symbols.
  if t:find("%l") or t:find("[\128-\255]") then n = n + 1 end
  if t:find("%u") then n = n + 1 end
  if t:find("%d") then n = n + 1 end
  if t:find("[^%w\128-\255]") then n = n + 1 end
  return n
end

local function wordPart(p)
  if p:match("^%l+$") or p:match("^%u%l+$") or p:match("^%u+$") or p:match("^%d+$") or p:match("^%a%d%d?%d?$") then
    return true
  end
  local head, rest = p:match("^(%l*)(.*)$")
  local humps = 0
  local left = rest:gsub("%u%l+", function() humps = humps + 1; return "" end)
  return left == "" and ((#head > 0 and humps >= 1) or (#head == 0 and humps >= 2))  -- camelCase, PascalCase
end

local function domainLike(t)
  if not t:match("^[%w%-%.]+$") or not t:find(".", 1, true) or t:find("..", 1, true) then return false end
  local tld = t:match("%.(%a+)$")
  return tld ~= nil and #tld >= 2 and #tld <= 12
end

local function passwordLike(t)
  if #t < 8 or #t > 64 or t:find("%s") or classes(t) < 3 then return false end
  if t:find("://", 1, true) or t:match("^www%.") or t:match("^[^@%s]+@[^@%s]+%.%a%a+$") or domainLike(t)
      or t:match("^[/~]") or t:match("^%.%.?/") or t:match("^[%w%.%-_]+/[%w%.%-_/]+$")
      or t:match("^%x%x%x%x%x%x%x%x%-%x%x%x%x%-%x%x%x%x%-%x%x%x%x%-%x%x%x%x%x%x%x%x%x%x%x%x$")
      or t:match("^%d%d%d%d%-%d%d%-%d%d") or t:match("^v?%d+[%.%d]*%.%d+[%-%+]?[%w%.]*$")
      or t:match("^[%w%.%$_]+%(.*%)$") or t:match("^[@#]") or t:match("^%-%-") then
    return false
  end
  local all = true
  for p in t:gmatch("[^%-_%.:/]+") do
    if not wordPart(p) then all = false; break end
  end
  return not all  -- snake_case_42, Hello-World and README.md are words, not passwords
end

-- For one copied item: the rule that makes the whole of it a secret, or nil (same contract as redact.secret_rule).
local function trim(s)  -- linear, unlike s:match("^%s*(.-)%s*$") on a long run of spaces
  local a = s:find("%S")
  if not a then return "" end
  local b = #s
  while s:find("^%s", b) do b = b - 1 end
  return s:sub(a, b)
end

local function secretRule(text)
  local t = trim(text)
  if t:find("%-%-%-%-%-BEGIN [%u%d ]*PRIVATE KEY") then return "private-key" end
  if (t:match("^%d+$") and #t >= 4 and #t <= 8) or t:match("^%d%d%d[ %-]%d%d%d$") or t:match("^%d%d%d%d[ %-]%d%d%d%d$") then
    return "otp"
  end
  if t:find("\n") or #t > 1000 then return nil end
  local masked, hit = maskAll(t)
  if t:find("%s") then
    -- A sentence that holds a key is masked, not dropped; a short `export X_TOKEN=…` line is a secret.
    if hit == "authorization" then return hit end
    if hit == "assignment" and #t <= 200 then return hit end
    if hit and masked:gsub("%[secret%]", ""):match("^%s*$") then return hit end
    return nil
  end
  if hit then return hit end
  return passwordLike(t) and "password-like" or nil
end

M.secretRule, M.maskAll = secretRule, maskAll  -- for testing from `hs -c`

