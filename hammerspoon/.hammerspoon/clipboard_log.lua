M.HOLD = 60          -- seconds a text copy waits for a clear-after-copy
M.KEEP_DAYS = 30     -- day files older than this are deleted
M.MAX_CHARS = 20000
M.PB = nil           -- the pasteboard watched: nil = the general one (tests swap in a private one)

